#include "libft.h"

static size_t	countwords(char const *s, char c)
{
	size_t	count;
	size_t	i;

	count = 0;
	i = 0;
	while (s[i])
	{
		while (s[i] && s[i] == c)
			i++;
		if (s[i])
			count++;
		while (s[i] && s[i] != c)
			i++;
	}
	return (count);
}

static char	**freesplit(char **result, size_t j)
{
	size_t	i;

	i = 0;
	while ((i < j) && result[i] != NULL)
		i++;
	if (i == j)
		return (result);
	i = 0;
	while (i < j)
	{
		free(result[i]);
		i++;
	}
	free(result);
	return (NULL);
}

char	**ft_split(char const *s, char c)
{
	char	**result;
	size_t	i;
	size_t	j;
	size_t	start;

	if (s == NULL)
		return (NULL);
	result = (char **)malloc(sizeof(char *) * (countwords(s, c) + 1));
	if (!result)
		return (NULL);
	i = 0;
	j = 0;
	while (s[i])
	{
		while (s[i] && s[i] == c)
			i++;
		start = i;
		while (s[i] && s[i] != c)
			i++;
		if (i > start)
			result[j++] = ft_substr(s, start, i - start);
	}
	result[j] = NULL;
	result = freesplit(result, j);
	return (result);
}
